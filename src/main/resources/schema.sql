DROP TABLE IF EXISTS reservation;
DROP TABLE IF EXISTS emprunt;
DROP TABLE IF EXISTS exemplaire;
DROP TABLE IF EXISTS adherent;

CREATE TABLE adherent (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom               VARCHAR(100) NOT NULL,
    prenom            VARCHAR(100) NOT NULL,
    email             VARCHAR(200) NOT NULL,
    categorie         VARCHAR(20)  NOT NULL,      -- ETUDIANT ou STANDARD
    suspendu_jusqu_au DATE
);

CREATE TABLE exemplaire (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    isbn   VARCHAR(20)  NOT NULL,
    titre  VARCHAR(200) NOT NULL,
    statut VARCHAR(20)  NOT NULL                  -- DISPONIBLE, EMPRUNTE ou RESERVE
);

CREATE TABLE emprunt (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    adherent_id        BIGINT NOT NULL REFERENCES adherent (id),
    exemplaire_id      BIGINT NOT NULL REFERENCES exemplaire (id),
    date_emprunt       DATE   NOT NULL,
    date_retour_prevue DATE   NOT NULL,
    date_retour        DATE                       -- null tant que le document n'est pas rendu
);

CREATE TABLE reservation (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    adherent_id      BIGINT       NOT NULL REFERENCES adherent (id),
    isbn             VARCHAR(20)  NOT NULL,
    date_reservation TIMESTAMP    NOT NULL
);
